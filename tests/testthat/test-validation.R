test_that("pedigree input and date errors are rejected", {
  p <- data.frame(ID = c("a", "b"), Sire = c(NA, "a"), Dam = NA)
  expect_error(sort_pedigree(NULL), "requires")
  expect_error(sort_pedigree(transform(p, Birth_Date = c("nope", NA))), "Invalid")
  expect_error(sort_pedigree(transform(p, Birth_Date = 1:2)), "Date")
  expect_error(sort_pedigree(transform(p, Birth_Date = c("2021-01-01", "2020-01-01"))), "precede")
  expect_error(sort_pedigree(transform(p, Dam = c(NA, "a"))), "differ")
  expect_error(pedigree_relationship(p, max_animals = 1), "guard")
  q <- sort_pedigree(transform(p, Sire = c("0", "a"), Dam = ""))
  expect_true(is.na(q$Sire[1]))
  expect_equal(pedigree_relationship(p, inverse = FALSE)$A["a", "b"], .5)
  expect_null(pedigree_relationship(p, inverse = FALSE)$A_inverse)
})
test_that("EM validates controls and input and reports likelihood", {
  expect_error(sequential_em(NULL, "x"), "data")
  expect_error(sequential_em(data.frame(x = c(1, Inf, 3)), "x"), "finite")
  expect_error(sequential_em(data.frame(x = c("a", "b", "c")), "x"), "numeric")
  expect_error(sequential_em(data.frame(x = 1:5), "x", tol = 0), "controls")
  expect_error(sequential_em(data.frame(x = 1:5), "x", max_iter = 0), "controls")
  set.seed(24)
  x <- rnorm(80)
  y <- x + rnorm(80)
  z <- x + y + rnorm(80)
  d <- data.frame(x = x, y = y, z = z)
  d$y[1:30] <- NA
  d$z[1:10] <- NA
  a <- sequential_em(d, c("x", "y", "z"), predictors = "all")
  expect_false(anyNA(a$data))
  expect_true(all(diff(a$log_likelihood[[2]]) >= -1e-8))
  expect_error(sequential_em(d, c("x", "y"), max_iter = 1, tol = 1e-30), "converge")
  expect_error(sequential_em(data.frame(x = rep(1, 5), y = c(1, 2, 3, NA, NA)), c("x", "y")), "rank")
  expect_error(sequential_em(data.frame(x = c(1, 1, 1, NA)), "x"), "variance")
})
test_that("reshaping preserves ID and trait order and checks reserved names", {
  d <- data.frame(ID = letters[1:5], x = 1:5, y = 6:10)
  l <- reshape_traits(d, c("y", "x"))
  expect_equal(l$.ga_y, c(6:10, 1:5))
  expect_equal(as.character(l$ID), rep(letters[1:5], 2))
  expect_error(reshape_traits(transform(d, ID = "a"), "x"), "unique")
  expect_error(reshape_traits(transform(d, .ga_y = 1), "x"), "Reserved")
})
test_that("model and pipeline validation fail before fitting", {
  d <- data.frame(ID = letters[1:5], x = 1:5, Sex = c("F", "M", "F", "M", "F"))
  A <- diag(5)
  dimnames(A) <- list(letters[1:5], letters[1:5])
  expect_error(fit_animal_model(d, "x", A, fixed = x ~ 1), "one-sided")
  expect_error(fit_animal_model(d, "x", A, n_iters = 1), "controls")
  expect_error(fit_animal_model(d, "x", A, max_records = 1), "guard")
  expect_error(fit_animal_model(d, "x", unname(A)), "symmetric")
  A2 <- A
  A2[1, 1] <- -1
  expect_error(fit_animal_model(d, "x", A2), "positive")
  expect_error(fit_animal_model(transform(d, x = c(NA, 2:5)), "x", A), "Complete")
  expect_error(fit_animal_model(d, "x", A, fixed = ~x), "predictors")
  expect_error(fit_animal_model(transform(d, Sex = c(NA, "M", "F", "M", "F")), "x", A, fixed = ~Sex), "Missing")
  expect_error(fit_animal_model(transform(d, z = 1), "x", A, fixed = ~z), "rank")
  p <- data.frame(ID = letters[1:4], Sire = NA, Dam = NA)
  expect_error(run_genetic_analysis(backend = "sommer", p, d, "x"), "Every")
  expect_error(check_control(list(tol = 1, tol = 2), "tol"), "control")
})
