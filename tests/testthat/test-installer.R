test_that("explicit installer checks downloads and never overwrites without consent", {
  path <- tempfile()
  on.exit(unlink(path, recursive = TRUE), add = TRUE)
  magic <- as.raw(rep(0, 20))
  magic[1:5] <- as.raw(c(127, 69, 76, 70, 2))
  magic[19] <- as.raw(62)
  local_mocked_bindings(curl_download = function(url, destfile, ...) {
    writeBin(magic, destfile)
    invisible(destfile)
  }, .package = "curl")
  res <- install_blupf90(path, check_runtime = FALSE)
  expect_true(file.exists(res$executable))
  expect_false(res$runtime_checked)
  expect_equal(nchar(res$SHA256), 64)
  expect_error(install_blupf90(path, check_runtime = FALSE), "already exists")
  expect_error(install_blupf90(tempfile(), overwrite = NA), "flag")
  expect_error(install_blupf90(NULL), "directory")
  expect_error(install_blupf90(tempfile(), ca_bundle = "/missing/ca"), "CA bundle")
})

test_that("installer rejects non-executable responses before any execution", {
  path <- tempfile()
  on.exit(unlink(path, recursive = TRUE), add = TRUE)
  local_mocked_bindings(curl_download = function(url, destfile, ...) {
    writeLines("<html>not a binary</html>", destfile)
    invisible(destfile)
  }, .package = "curl")
  expect_error(install_blupf90(path, check_runtime = FALSE), "ELF")
  expect_false(file.exists(file.path(path, "blupf90+")))
})

test_that("runner rejects unsafe controls and detects native process failures", {
  x <- make_example(1)
  expect_error(fit_blupf90_model(x$p, x$d, x$traits, executable = NA), "executable")
  expect_error(fit_blupf90_model(x$p, x$d, x$traits, executable = Sys.which("true"), timeout = 0), "timeout")
  expect_error(fit_blupf90_model(x$p, x$d, x$traits, executable = Sys.which("true"), keep_files = NA), "keep_files")
  expect_error(fit_blupf90_model(x$p, x$d, x$traits, executable = Sys.which("true"), job_root = "/missing"), "job_root")
  path <- tempfile()
  dir.create(path)
  on.exit(unlink(path, recursive = TRUE), add = TRUE)
  expect_error(run_native_blup(Sys.which("false"), "bad.par", path, "failure", 5, 1), "failed")
  expect_error(run_native_blup("/missing/executable", "bad.par", path, "failure", 5, 1), "could not complete")
  expect_error(run_genetic_analysis(x$p, x$d, x$traits, backend = "blupf90", model_control = list(tol = 1)), "blupf90_control")
  expect_error(run_genetic_analysis(x$p, x$d, x$traits, backend = "sommer", blupf90_control = list(tol = 1)), "only for")
  expect_error(run_genetic_analysis(x$p, x$d, x$traits, backend = "sommer", impute = NA), "logical")
  expect_error(run_genetic_analysis(x$p, x$d, x$traits, backend = "sommer", max_animals = 1), "max_animals")
})
